#!/usr/bin/env python3
"""The paper moth's alpha cut, sampled into braille cells.

`docs/media/paper-moth-master.png` carries the figure in its alpha channel: paper
on a cleared ground. This samples that alpha at braille dot positions, so the
terminal shows the silhouette the app icon shows. A braille cell is two dots wide
and four tall, which is square on a terminal cell of 1:2, so a dot grid in the
cut's own proportions keeps them.

Usage
    ./.venv/bin/python scripts/generate_terminal_mark.py            # print
    ./.venv/bin/python scripts/generate_terminal_mark.py --write    # update ui/terminal_mark.py
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "docs" / "media" / "paper-moth-master.png"
TARGET = ROOT / "ui" / "terminal_mark.py"

#: Dot grids as (width, height): the greeting's mark, and the header's three lines.
MARK_GRID: tuple[int, int] = (20, 20)
HEAD_GRID: tuple[int, int] = (20, 12)

#: Alpha below the floor is the cleared ground; a dot lights above the threshold.
INK_FLOOR = 40
DOT_THRESHOLD = 120

#: Braille bits per (column, row) inside a cell: dots 1-3 and 7 left, 4-6 and 8 right.
DOTS = ((0x01, 0x02, 0x04, 0x40), (0x08, 0x10, 0x20, 0x80))


def cut(source: Image.Image | None = None) -> Image.Image:
    """The alpha channel trimmed to the silhouette's own box."""
    image = (Image.open(SOURCE) if source is None else source)
    alpha = image.convert("RGBA").getchannel("A")
    box = alpha.point(lambda value: 255 if value > INK_FLOOR else 0).getbbox()
    return alpha.crop(box) if box else alpha


def braille(image: Image.Image, grid: tuple[int, int]) -> list[str]:
    """The cut folded into rows of braille cells, empty rows trimmed."""
    cols, rows = grid[0] - grid[0] % 2, grid[1] - grid[1] % 4
    dots = image.resize((cols, rows), Image.LANCZOS)
    lines: list[str] = []
    for top in range(0, rows, 4):
        line: list[str] = []
        for left in range(0, cols, 2):
            mask = 0
            for dx in (0, 1):
                for dy in range(4):
                    if dots.getpixel((left + dx, top + dy)) >= DOT_THRESHOLD:
                        mask |= DOTS[dx][dy]
            line.append(chr(0x2800 + mask) if mask else " ")
        lines.append("".join(line).rstrip())
    while lines and not lines[0]:
        lines.pop(0)
    while lines and not lines[-1]:
        lines.pop()
    return lines


BANNER = '''"""The paper moth's alpha cut, folded into braille cells.

Generated by `scripts/generate_terminal_mark.py --write`; edit the master or the
generator, never this file.
"""

#: Dot grids the generator was run at, so the provenance test re-renders the same
#: cuts instead of guessing a size.
MARK_GRID: tuple[int, int] = {mark_grid!r}
MARK_HEAD_GRID: tuple[int, int] = {head_grid!r}

#: The greeting's mark, one string per terminal line.
MARK_ROWS: tuple[str, ...] = (
{mark})

#: The header mark, beside the wordmark.
MARK_HEAD: tuple[str, ...] = (
{head})
'''


def module_source(mark: list[str], head: list[str]) -> str:
    return BANNER.format(
        mark_grid=MARK_GRID,
        head_grid=HEAD_GRID,
        mark="".join(f"    {line!r},\n" for line in mark),
        head="".join(f"    {line!r},\n" for line in head),
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()

    image = cut()
    mark = braille(image, MARK_GRID)
    head = braille(image, HEAD_GRID)
    if args.write:
        TARGET.write_text(module_source(mark, head), encoding="utf-8")
        print(f"wrote {TARGET.relative_to(ROOT)} "
              f"({MARK_GRID[0]}x{MARK_GRID[1]} and {HEAD_GRID[0]}x{HEAD_GRID[1]} dots)")
    else:
        print("\n".join(mark))
        print()
        print("\n".join(head))
    return 0


if __name__ == "__main__":
    sys.exit(main())
