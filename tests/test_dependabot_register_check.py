"""An open alert no register row decides is a defect that today only a human noticed.

Alert #1 on the security tab (glib, GHSA-wrw7-89jp-8q8g) sat open while the register
carried a row nobody in CI had ever compared against the alert list — the register and
the platform drifted independently, and both reads stayed self-congratulatory. The
owner rule of 2026-11-24 names the invariant: every open alert carries a registered,
checkable decision, and a row claiming `state=fixed` matches the lockfile its ecosystem
names. `scripts/dependabot_register_check.py` is that comparison, and this file holds
it to account: the mutation cases delete a row or plant a lock below a fixed row's
floor and demand the finding come back, because a checker that rejects nothing counts
as never built. The exit-2 cases guard the one shape a supply-chain gate must never
take: reading nothing and reporting green.

The script is stdlib-only Python, so it is imported directly; the workflow is YAML, so
it is read as data — the same reason tests/test_registry_guard_in_ci.py parses it.
"""
from __future__ import annotations

import importlib.util
import json
import urllib.error
from pathlib import Path

import pytest
import yaml

ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / "scripts" / "dependabot_register_check.py"
WORKFLOW = ROOT / ".github" / "workflows" / "supply-chain.yml"

_spec = importlib.util.spec_from_file_location("dependabot_register_check", SCRIPT)
checker = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(checker)


def _alert(number: int, ghsa: str | None, cve: str | None,
           name: str, ecosystem: str) -> dict:
    return {
        "number": number,
        "dependency": {"package": {"name": name, "ecosystem": ecosystem}},
        "security_advisory": {"ghsa_id": ghsa, "cve_id": cve},
        "state": "open",
    }


def _cargo_lock(pairs: list[tuple[str, str, str | None]]) -> str:
    blocks = []
    for name, version, source in pairs:
        block = f'[[package]]\nname = "{name}"\nversion = "{version}"\n'
        if source is not None:
            block += f'source = "{source}"\n'
        blocks.append(block)
    return "# Generated by cargo\nversion = 3\n\n" + "\n".join(blocks)


def _tree(tmp_path: Path, cargo: list[tuple[str, str, str | None]],
          uv: list[tuple[str, str, str | None]] | None = None) -> Path:
    (tmp_path / "app" / "src-tauri").mkdir(parents=True)
    (tmp_path / "app" / "src-tauri" / "Cargo.lock").write_text(
        _cargo_lock(cargo), encoding="utf-8")
    if uv is not None:
        (tmp_path / "uv.lock").write_text(_cargo_lock(uv), encoding="utf-8")
    return tmp_path


GLIB_ROW = ("GHSA-wrw7-89jp-8q8g  # package=glib ecosystem=crates.io scope=runtime "
            "state=pending-fix affected=>=0.15.0,<0.20.0 fixed_in=0.20.0 "
            "blocked_by=gtk-pins-glib-0.18 recheck=2026-12-24")


def _register(tmp_path: Path, lines: list[str]) -> Path:
    path = tmp_path / "advisories-ignore.txt"
    path.write_text("# header\n\n" + "\n".join(lines) + "\n", encoding="utf-8")
    return path


def test_an_open_alert_without_a_row_is_a_finding(tmp_path):
    """GIVEN the real glib alert and a register missing its row THEN the finding names
    the alert number, the advisory id and the package; deleting a row must not be a
    silent pass."""
    root = _tree(tmp_path, [("glib", "0.18.5", "registry+https://crates.io-index")])
    register = _register(tmp_path, ["# the glib row is gone"])
    findings = checker.evaluate(
        [_alert(1, "GHSA-wrw7-89jp-8q8g", None, "glib", "rust")],
        checker.parse_register(register), root, str(register))
    assert len(findings) == 1
    assert "#1" in findings[0]
    assert "ghsa-wrw7-89jp-8q8g" in findings[0]
    assert "glib" in findings[0]


def test_a_covered_alert_and_a_matching_fixed_row_pass_clean(tmp_path):
    """GIVEN the alert covered by its row and a fixed row whose package sits at the
    floor in Cargo.lock THEN nothing is reported — the green is earned, not assumed."""
    root = _tree(tmp_path, [
        ("glib", "0.18.5", "registry+https://crates.io-index"),
        ("sidecar-crate", "1.2.4", "registry+https://crates.io-index"),
    ])
    register = _register(tmp_path, [
        GLIB_ROW,
        "GHSA-mock-0000-0001  # package=sidecar-crate ecosystem=crates.io "
        "scope=runtime state=fixed affected=<1.2.4 fixed_in=1.2.4 recheck=2026-12-24",
    ])
    findings = checker.evaluate(
        [_alert(1, "GHSA-wrw7-89jp-8q8g", None, "glib", "rust")],
        checker.parse_register(register), root, str(register))
    assert findings == []


def test_a_fixed_row_below_its_lock_floor_is_a_finding(tmp_path):
    """GIVEN a row that claims the advisory is fixed at 0.20.0 WHILE Cargo.lock still
    resolves the crate at 0.18.5 THEN the row is reported with both versions — prose
    may not retire what the lock still carries."""
    root = _tree(tmp_path, [("glib", "0.18.5", "registry+https://crates.io-index")])
    register = _register(tmp_path, [
        "GHSA-wrw7-89jp-8q8g  # package=glib ecosystem=crates.io scope=runtime "
        "state=fixed affected=>=0.15.0,<0.20.0 fixed_in=0.20.0 recheck=2026-12-24",
    ])
    findings = checker.evaluate([], checker.parse_register(register), root, str(register))
    assert len(findings) == 1
    assert "0.18.5" in findings[0] and "0.20.0" in findings[0]


def test_a_development_pypi_row_may_name_tooling_no_lock_carries(tmp_path):
    """GIVEN a fixed PyPI row for CI tooling absent from uv.lock THEN scope decides:
    development is the register's own wording for installer-pinned tooling, runtime is
    a dependency the lock was supposed to carry."""
    root = _tree(tmp_path, [("glib", "0.18.5", None)], uv=[])
    dev = _register(tmp_path, [
        "PYSEC-2026-4321  # package=uv ecosystem=PyPI scope=development state=fixed "
        "affected=<=0.13.3 fixed_in=0.13.4 recheck=2026-12-23"])
    assert checker.evaluate([], checker.parse_register(dev), root, str(dev)) == []
    runtime = _register(tmp_path, [
        "PYSEC-2026-9999  # package=requests ecosystem=PyPI scope=runtime state=fixed "
        "affected=<2.32.0 fixed_in=2.32.0 recheck=2026-12-23"])
    findings = checker.evaluate([], checker.parse_register(runtime), root, str(runtime))
    assert len(findings) == 1
    assert "does not carry the package" in findings[0]


def test_a_hyphenated_crate_name_is_matched_across_the_spelling(tmp_path):
    """GIVEN the register writes block_buffer and Cargo.lock names block-buffer THEN
    the floor check finds the crate; one typo must not read as an absent package."""
    root = _tree(tmp_path, [("block-buffer", "0.12.1", "registry+https://crates.io-index")])
    register = _register(tmp_path, [
        "GHSA-qwgh-2vcv-g2f7  # package=block_buffer ecosystem=crates.io "
        "scope=development state=fixed affected=>=0.10.0,<0.12.1 fixed_in=0.12.1 "
        "recheck=2026-11-27"])
    assert checker.evaluate([], checker.parse_register(register), root, str(register)) == []


def test_a_git_sourced_lock_entry_is_a_finding(tmp_path):
    """GIVEN a lock entry resolved from a foreign git repository WHILE its version
    string stays untouched THEN the check reports it — scripts/lockfile_check.py never
    reads a source line, so this is the only gate that sees the fork swap."""
    registry_lock = _tree(tmp_path, [("serde", "1.0.229", "registry+https://crates.io-index")])
    assert checker.evaluate([], [], registry_lock, "register") == []
    forked = _tree(tmp_path / "fork", [("serde", "1.0.229",
                                        "git+https://someone-else.example/serde.git?rev=deadbeef")])
    findings = checker.evaluate([], [], forked, "register")
    assert len(findings) == 1
    assert "someone-else.example" in findings[0]


def test_main_refuses_to_pass_when_the_alert_list_cannot_be_read(tmp_path, monkeypatch, capsys):
    """GIVEN CI without a token, and a token the API refuses THEN both exits are 2 and
    say nothing was checked — an unreadable alert list must never render as a pass."""
    monkeypatch.delenv("GITHUB_TOKEN", raising=False)
    monkeypatch.delenv("GITHUB_ACTIONS", raising=False)
    root = _tree(tmp_path, [("glib", "0.18.5", None)])
    register = _register(tmp_path, [GLIB_ROW])
    rc = checker.main(["--fetch", "--repo", "o/r", "--register", str(register),
                       "--root", str(root)])
    out = capsys.readouterr().out
    assert rc == 2
    assert "nothing was checked" in out and "not a pass" in out

    monkeypatch.setenv("GITHUB_TOKEN", "s-t")

    def refuse(*args, **kwargs):
        raise urllib.error.HTTPError("https://api.github.com", 403, "Forbidden", None, None)

    monkeypatch.setattr(checker.urllib.request, "urlopen", refuse)
    rc = checker.main(["--fetch", "--repo", "o/r", "--register", str(register),
                       "--root", str(root)])
    out = capsys.readouterr().out
    assert rc == 2
    assert "HTTP 403" in out and "not a pass" in out

    missing = tmp_path / "no-such-alerts.json"
    rc = checker.main(["--alerts", str(missing), "--register", str(register),
                       "--root", str(root)])
    assert rc == 2


def test_main_exits_zero_clean_and_one_with_a_finding(tmp_path, monkeypatch, capsys):
    """GIVEN the same planted inputs as the unit cases THEN the CLI returns 0 clean and
    1 when a row is deleted — the gate's number is the comparison's number."""
    monkeypatch.delenv("GITHUB_ACTIONS", raising=False)
    root = _tree(tmp_path, [("glib", "0.18.5", "registry+https://crates.io-index")])
    register = _register(tmp_path, [GLIB_ROW])
    alerts = tmp_path / "alerts.json"
    alerts.write_text(json.dumps(
        [_alert(1, "GHSA-wrw7-89jp-8q8g", None, "glib", "rust")]), encoding="utf-8")
    assert checker.main(["--alerts", str(alerts), "--register", str(register),
                         "--root", str(root)]) == 0
    register.write_text("# header\n\n# row deleted for the mutation case\n",
                        encoding="utf-8")
    assert checker.main(["--alerts", str(alerts), "--register", str(register),
                         "--root", str(root)]) == 1


def _advisories_job() -> dict:
    return yaml.safe_load(WORKFLOW.read_text(encoding="utf-8"))["jobs"]["advisories"]


def _coverage_steps(steps: list[dict]) -> list[dict]:
    return [s for s in steps if isinstance(s.get("run"), str)
            and "dependabot_register_check.py" in s["run"]]


def test_the_advisories_job_fetches_the_alert_list_and_stays_blocking():
    """GIVEN supply-chain.yml THEN the advisories job runs the checker against the live
    alert list, blocks on its exit code, and holds exactly the extra scope the fetch
    needs: contents plus security-events, both read-only."""
    job = _advisories_job()
    found = _coverage_steps(job["steps"])
    assert len(found) == 1
    step = found[0]
    assert "--fetch" in step["run"]
    assert "|| true" not in step["run"]
    assert step.get("continue-on-error") is None
    assert "GITHUB_TOKEN" in step["env"]
    assert job["permissions"] == {"contents": "read", "security-events": "read"}


def test_a_workflow_without_the_step_is_caught_by_the_same_search():
    """GIVEN the step removed in memory THEN the search comes back empty: the workflow
    test fails when the step disappears, it does not shrug."""
    job = _advisories_job()
    remaining = [s for s in job["steps"] if s not in _coverage_steps(job["steps"])]
    assert _coverage_steps(remaining) == []
