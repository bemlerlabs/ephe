"""The shell command list and the workbench grant are one list.

The access-control layer used to stay off, so a local webview could call every
registered command. The workbench grant is the permission set `workbench`.
The three surface commands lead that set. A surface window's capability stays
empty. The door matches the three names. A shared prefix admits nothing.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LIB_RS = ROOT / "app" / "src-tauri" / "src" / "lib.rs"
BUILD_RS = ROOT / "app" / "src-tauri" / "build.rs"
OPTIONS_RS = ROOT / "app" / "src-tauri" / "src" / "plugin_window_options.rs"
WORKBENCH_SET = ROOT / "app" / "src-tauri" / "permissions" / "workbench.toml"
WORKBENCH_CAP = ROOT / "app" / "src-tauri" / "capabilities" / "workbench-commands.json"
SURFACE_CAP = ROOT / "app" / "src-tauri" / "capabilities" / "plugin-window.json"
GENERATED = ROOT / "app" / "src-tauri" / "permissions" / "autogenerated"

SURFACE = (
    "plugin_window_open",
    "plugin_window_close",
    "plugin_window_bounds",
)


def _handler_names() -> list[str]:
    source = LIB_RS.read_text(encoding="utf-8")
    handler = re.search(r"generate_handler!\[(.*?)\]", source, re.S)
    assert handler, "lib.rs registers no command list"
    names = []
    for entry in handler.group(1).split(","):
        entry = re.sub(r"//[^\n]*", "", entry).strip()
        if entry:
            names.append(entry.rsplit("::", 1)[-1])
    return names


def _acl_names() -> list[str]:
    source = BUILD_RS.read_text(encoding="utf-8")
    block = re.search(r"\.commands\(&\[(.*?)\]\)", source, re.S)
    assert block, "build.rs does not hand AppManifest a command list"
    return re.findall(r'"([a-z0-9_]+)"', block.group(1))


def _set_allows() -> list[str]:
    text = WORKBENCH_SET.read_text(encoding="utf-8")
    body = text.split("permissions = [", 1)[1].split("]", 1)[0]
    return re.findall(r'"(allow-[a-z0-9-]+)"', body)


def _allow(command: str) -> str:
    return "allow-" + command.replace("_", "-")


def test_the_workbench_grant_is_the_registered_list_with_the_surface_commands_first():
    registered = _handler_names()
    acl = _acl_names()
    allows = _set_allows()
    assert acl[:3] == list(SURFACE)
    assert allows[:3] == [_allow(name) for name in SURFACE]
    assert acl == [_allow_to_command(item) for item in allows]
    assert set(acl) == set(registered)
    assert len(acl) == len(registered) == len(set(acl))


def _allow_to_command(allow: str) -> str:
    return allow.removeprefix("allow-").replace("-", "_")


def test_each_window_label_is_told_which_commands_it_can_call():
    grant = json.loads(WORKBENCH_CAP.read_text(encoding="utf-8"))
    surface = json.loads(SURFACE_CAP.read_text(encoding="utf-8"))
    assert grant["identifier"] == "workbench-commands"
    assert grant["webviews"] == ["main"]
    assert grant.get("windows", []) == []
    assert grant["permissions"] == ["workbench"]
    assert grant["local"] is True
    assert "remote" not in grant
    assert surface["windows"] == ["ephe-plugin-*"]
    assert surface["permissions"] == []
    assert surface["local"] is True
    dumped = json.dumps(surface)
    assert "workbench" not in surface["permissions"]
    for name in SURFACE:
        assert _allow(name) not in dumped


def test_the_generated_allow_files_match_the_list():
    for name in _acl_names():
        body = (GENERATED / f"{name}.toml").read_text(encoding="utf-8")
        assert f'commands.allow = ["{name}"]' in body


def test_the_door_matches_the_three_names_and_a_prefix_does_not_admit():
    source = OPTIONS_RS.read_text(encoding="utf-8")
    listed = re.search(r"SURFACE_COMMANDS: \[&str; 3\] = \[(.*?)\]", source, re.S)
    assert listed, "the surface door has no explicit three-name list"
    names = re.findall(r'"([a-z0-9_]+)"', listed.group(1))
    assert names == list(SURFACE)
    function = source.split("pub fn is_surface_command", 1)[1].split("pub fn ", 1)[0]
    assert "starts_with" not in function
    assert "SURFACE_COMMANDS" in function
