_TEMPLATES = {
    "python-cli": ("python", _python_template),
    "python-api": ("python", _python_template),
    "node-cli": ("node", _node_cli_files),
    "web-app": ("web", _web_app_files),
    "generic": ("docs", _common_files),
}


def _write_manifest_files(root: str, files: dict[str, str]) -> list[str]:
    written: list[str] = []
    for rel, content in files.items():
        rel = _safe_relative(rel)
        full = os.path.join(root, rel.replace("/", os.sep))
        parent = os.path.dirname(full)
        if not os.path.isdir(parent):
            os.makedirs(parent)
        with open(full, "w", encoding="utf-8") as fh:
            fh.write(content)
        written.append(rel)
    return written


async def scaffold_project(
    target_dir: str,
    template: str = "python-cli",
    project_name: str = "",
    description: str = "",
    author: str = "ephe",
) -> str:
    """Creates a complete, verified project skeleton in one call.

    Writes manifest, sources, real tests, docs, license and gitignore, then
    verifies the result structurally. Only a PROJECT_SCAFFOLD_VERIFIED answer
    may be relayed as finished. Refuses to touch non-empty directories.
    """
    template = (template or "python-cli").strip().lower()
    if template not in _TEMPLATES:
        allowed = ", ".join(sorted(_TEMPLATES))
        return f"[factory-error: unknown template '{template}'. Allowed: {allowed}]"
    try:
        root = _resolve_allowed_path(target_dir)
    except ValueError as exc:
        return f"[factory-error: {exc}]"
    if os.path.isdir(root) and os.listdir(root):
        probe = _verify(root, json.dumps({"kind": "project"}))
        if probe["metrics"].get("files", 0) > 0:
            return (f"[factory-error: target directory is not empty: {root}. "
                    "Choose a fresh subdirectory — existing content is never overwritten.]")
    name = _clean_name(project_name or os.path.basename(root))
    title = (project_name or name).strip()
    files = dict(_TEMPLATES[template][1](name, title, description, author))
    if template == "python-api":
        mod = name.replace("-", "_")
        files[f"src/{mod}/core.py"] = (
            '"""Core logic for the generated API service (extend freely)."""\n'
            "from __future__ import annotations\n\n\n"
            "def health() -> dict[str, str]:\n"
            '    """Liveness probe used by tests and operators."""\n'
            '    return {"status": "ok", "service": "generated"}\n\n\n'
            "def routes() -> list[str]:\n"
            '    """Declared route table (placeholder, fill with endpoints)."""\n'
            '    return ["/health", "/version"]\n'
        )
    try:
        written = _write_manifest_files(root, files)
    except OSError as exc:
        return f"[factory-error: writing failed: {exc}]"
    required = [r for r in ("README.md", "LICENSE", ".gitignore", "Makefile", "docs/USAGE.md") if r in files]
    report = _verify(root, json.dumps({"kind": "project", "min_files": max(5, len(files) - 2),
                                       "required_files": required}))
    payload = {"path": root, "template": template, "name": name, "written": written,
               "checks": report["metrics"]}
    body = json.dumps(payload, ensure_ascii=False)
    if report["verified"]:
        return f"PROJECT_SCAFFOLD_VERIFIED: {body}"
    return f"PROJECT_SCAFFOLD_INCOMPLETE: {body} || failures={report['failures']}"
