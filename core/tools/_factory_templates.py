def _python_src_files(name: str, title: str) -> dict[str, str]:
    mod = name.replace("-", "_")
    core_src = (
        f'"""Core logic for {title}."""\n'
        "from __future__ import annotations\n\n"
        "import re\n\n\n"
        "def slugify(text: str) -> str:\n"
        '    """Lower-case, hyphenate, strip non-alphanumeric noise."""\n'
        '    cleaned = re.sub(r"[^A-Za-z0-9 ]+", "", text or "")\n'
        '    return "-".join(cleaned.lower().split())\n\n\n'
        "def summarize(items: list[str]) -> dict[str, int]:\n"
        '    """Return basic counters for a list of strings."""\n'
        "    return {\n"
        '        "count": len(items),\n'
        '        "non_empty": sum(1 for i in items if i.strip()),\n'
        '        "total_chars": sum(len(i) for i in items),\n'
        "    }\n"
    )
    main_src = (
        f'"""CLI entrypoint for {title}."""\n'
        "import argparse\n\n"
        "from .core import slugify, summarize\n\n\n"
        f"def main(argv: list[str] | None = None) -> int:\n"
        f"    parser = argparse.ArgumentParser(prog={mod!r})\n"
        '    parser.add_argument("--text", default="", help="text to slugify")\n'
        '    parser.add_argument("--count", action="store_true",\n'
        '                      help="also print a word summary")\n'
        "    args = parser.parse_args(argv)\n"
        "    if args.text:\n"
        "        print(slugify(args.text))\n"
        "        if args.count:\n"
        "            print(summarize(args.text.split()))\n"
        "    return 0\n\n\n"
        'if __name__ == "__main__":\n'
        "    raise SystemExit(main())\n"
    )
    test_src = (
        "import sys\n"
        "from pathlib import Path\n\n"
        'sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))\n\n'
        f"from {mod} import __version__\n"
        f"from {mod} import core\n\n\n"
        "def test_version_is_a_string():\n"
        "    assert isinstance(__version__, str) and __version__\n\n\n"
        "def test_slugify_basic():\n"
        '    assert core.slugify("Hello, World!!") == "hello-world"\n\n\n'
        "def test_summarize_counts():\n"
        '    stats = core.summarize(["a", "", "bb"])\n'
        '    assert stats["count"] == 3\n'
        '    assert stats["non_empty"] == 2\n'
        '    assert stats["total_chars"] == 3\n'
    )
    return {
        f"src/{mod}/__init__.py": (
            f'"""{title} - generated by the Ephe Project Factory."""\n\n'
            '__version__ = "0.1.0"\n'
        ),
        f"src/{mod}/core.py": core_src,
        f"src/{mod}/__main__.py": main_src,
        "tests/test_core.py": test_src,
        "run.py": (
            "#!/usr/bin/env python\n"
            '"""Launcher so the project runs with plain `python run.py` — no install step."""\n'
            "import os\nimport sys\n\n"
            'sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "src"))\n\n'
            f"from {mod}.__main__ import main\n\n\n"
            "if __name__ == \"__main__\":\n"
            "    raise SystemExit(main())\n"
        ),
    }


def _python_template(name, title, description, author):
    files = _common_files(name, title, description, author)
    files.update(_pyproject_files(name, title, description))
    files.update(_python_src_files(name, title))
    return files


def _node_cli_files(name: str, title: str, description: str, author: str) -> dict[str, str]:
    files = _common_files(name, title, description, author)
    files["package.json"] = json.dumps(
        {
            "name": name,
            "version": "0.1.0",
            "description": description or title,
            "type": "module",
            "main": "src/index.js",
            "scripts": {"test": "node --test tests/"},
            "license": "MIT",
        },
        indent=2,
    )
    files["Makefile"] = ".phony: test run\ntest:\n\tnpm test\nrun:\n\tnpm start -- --help\n"
    files["src/index.js"] = (
        f"/** {title} - generated by the Ephe Project Factory. */\n"
        "export function slugify(text) {\n"
        '  return (text || "").toLowerCase().replace(/[^a-z0-9 ]/g, "").trim().split(/\\s+/).join("-");\n'
        "}\n\n"
        "export function summarize(items) {\n"
        "  return {\n"
        "    count: items.length,\n"
        "    nonEmpty: items.filter((i) => i.trim().length).length,\n"
        "    totalChars: items.reduce((a, i) => a + i.length, 0),\n"
        "  };\n}\n"
    )
    files["tests/core.test.js"] = (
        "import { test } from 'node:test';\nimport assert from 'node:assert';\n"
        "import { slugify, summarize } from '../src/index.js';\n\n"
        "test('slugify lowercases and hyphenates', () => {\n"
        "  assert.equal(slugify('Hello, World!!'), 'hello-world');\n});\n\n"
        "test('summarize counts', () => {\n"
        "  const s = summarize(['a', '', 'bb']);\n"
        "  assert.equal(s.count, 3); assert.equal(s.nonEmpty, 2); assert.equal(s.totalChars, 4);\n});\n"
    )
    return files


