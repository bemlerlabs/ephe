"""R34 Project Factory: the scaffold half, one deterministic generator.

``scaffold_project`` lays out a runnable project skeleton — manifest, sources,
real tests, docs, gitignore, license — and hands it to
``core.tools.verify_tools._verify`` before any success string is returned, so
a skeleton that only looks finished fails at this step.

The tool writes files, so it travels the normal approval gate. Its success
string is the evidence that the structural check ran, and a playbook that
relays it must relay it unchanged.

The document half of the factory sits in ``_factory_brief.py``; both are
re-exported through ``factory_tools``, which is the path the registry imports.
"""
