def _clean_name(raw: str, fallback: str = "ephe-project") -> str:
    name = re.sub(r"\s+", "-", (raw or "").strip().lower())
    name = re.sub(r"[^A-Za-z0-9._-]", "", re.sub(r"[-_]+", "-", name))
    return name.strip("-._") or fallback


def _safe_relative(rel: str) -> str:
    rel = (rel or "").strip().strip("/")
    parts = [p for p in re.split(r"[\\/]+", rel) if p not in ("", ".", "..")]
    if not parts or re.search(r"[<>:\"|?*]", rel):
        raise ValueError(f"invalid file path: {rel!r}")
    return "/".join(parts)


