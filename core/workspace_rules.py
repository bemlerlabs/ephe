"""Ephe — workspace instruction files (R29, Wave 2/B2; CTX-CONTRACT v2).

Operative project rules live in the workspace itself. The resolver reads them in
one fixed order, and every source is optional:

1. ``AGENTS.md`` at the workspace root (the canonical file; built from parts so
   tooling cannot rewrite the token mid-flight).
2. ``.ephe/rules/*.md`` — the owner's decision 2026-10-18 that the workspace
   rules are read in addition to ``AGENTS.md``. Sorted by file name, one level,
   no recursion. A rule file may carry a ``paths:`` frontmatter list and then
   loads only when one of those globs could match a path in the current turn.
3. ``SOUL.md`` at the root, else ``.ephe/persona.md`` — the workspace's voice.
4. ``USER.md`` at the root, else ``.ephe/user.md`` — stable user preferences.
5. ``MEMORY.md`` — curated long-term notes, private contexts only.

Every file is provenance-marked, capped on its own and under a combined cap, and
reported back with the status the reader found — a file that was skipped or
refused is named in the report instead of disappearing. Both the prompt and the
stage display read this one module, so what the model receives and what the
surface says cannot drift.

``IDENTITY.md`` is deliberately not a layer: the identity block is generated by
the harness, and a persona belongs in ``SOUL.md``.

Resolution order for the workspace root comes from one authority,
``core.engine_config.get_workspace_dir()``: ``EPHE_WORKSPACE`` env (tests / power
users) → persisted engine.json → neutral ``~/Ephe``.
"""
from __future__ import annotations

import logging
import os
import re
from dataclasses import dataclass, field
from functools import lru_cache
from pathlib import Path

logger = logging.getLogger(__name__)

# Built from parts so tooling/normalizers cannot rewrite the token mid-flight.
RULES_NAME = "AGENT" + chr(83) + ".md"  # canonical rules file name
RULES_DIR = Path(".ephe") / "rules"
RULE_SUFFIX = ".md"

#: The optional overlays. The first file of each alias pair wins.
SOUL_NAME = "SOUL.md"
PERSONA_ALIAS = Path(".ephe") / "persona.md"
USER_NAME = "USER.md"
USER_ALIAS = Path(".ephe") / "user.md"
MEMORY_NAME = "MEMORY.md"

WORKSPACE_RULES_MAX = 12_000
#: One file may not crowd out the rest of the layer on its own.
RULE_FILE_MAX = 6_000
SOUL_FILE_MAX = 6_000
#: OpenClaw's USER.md budget, kept as the number the ecosystem documents.
USER_FILE_MAX = 4_000
MEMORY_FILE_MAX = 6_000
#: All layers together. The per-layer caps sum to this value; headers and
#: separators are paid out of it, so the assembled text never exceeds it.
WORKSPACE_CONTEXT_MAX = 28_000

#: Status words are the report's machine text: stable, English, one per outcome.
INCLUDED = "included"
TRUNCATED = "truncated"
EMPTY = "empty"
UNREADABLE = "unreadable"
DENIED = "denied"
SKIPPED = "skipped"

#: Layer names in precedence order. The enum is the report's vocabulary too.
LAYER_AGENTS = "agents"
LAYER_RULES = "rules"
LAYER_SOUL = "soul"
LAYER_USER = "user"
LAYER_MEMORY = "memory"

SCOPE_WORKSPACE = "workspace"
SCOPE_PRIVATE = "private"

#: The per-file cap each layer advertises in ``explain_workspace_context``.
LAYER_CAPS: dict[str, int] = {
    LAYER_AGENTS: RULE_FILE_MAX,
    LAYER_RULES: RULE_FILE_MAX,
    LAYER_SOUL: SOUL_FILE_MAX,
    LAYER_USER: USER_FILE_MAX,
    LAYER_MEMORY: MEMORY_FILE_MAX,
}


@dataclass(frozen=True)
class RuleFile:
    """One candidate file, as the resolver saw it."""

    name: str
    chars: int
    status: str
    reason: str = ""
    layer: str = LAYER_RULES
    scope: str = SCOPE_WORKSPACE


@dataclass(frozen=True)
class WorkspaceRules:
    """The prompt text plus the report the surface shows."""

    text: str | None
    files: tuple[RuleFile, ...] = field(default=())

    @property
    def total_chars(self) -> int:
        return len(self.text or "")


def workspace_key(path_or_identity=None) -> str:
    """W4 S3: normalized workspace key — the ONLY source for
    dedupe/cache/persistence/correlation.

    Identity: a relative path, its absolute path and a symlink pointing at
    the target all yield the same key. Rules:
      - an explicit identity (``path_or_identity``) wins, otherwise ``os.getcwd()``;
      - ``~`` expansion via ``Path.expanduser``;
      - ``resolve()`` (realpath) normalizes symlinks and fragment paths.

    The raw path stays only for I/O and for display in the state; as a
    cache/persistence key exactly this function serves.
    """
    # The workspace key is the identity of the user's own project root.
    # codeql[py/path-injection]
    return str(Path(path_or_identity or os.getcwd()).expanduser().resolve())


def resolve_workspace_dir() -> str:
    """Active workspace root: the one authority is ``engine_config.get_workspace_dir``."""
    from core.engine_config import get_workspace_dir

    return get_workspace_dir()


def _candidates(root: Path) -> list[Path]:
    """The rule files to read, in the one order that is deterministic."""
    out = [root / RULES_NAME]
    rules_dir = root / RULES_DIR
    try:
        if rules_dir.is_dir() and not rules_dir.is_symlink():
            out.extend(
                sorted(
                    (
                        entry
                        for entry in rules_dir.iterdir()
                        if entry.suffix == RULE_SUFFIX and entry.is_file()
                    ),
                    key=lambda entry: entry.name,
                )
            )
    except OSError as exc:
        logger.warning("Rules directory unreadable at %s: %s", rules_dir, exc)
    return out


def _bounded(body: str, limit: int, tail: str = "") -> str:
    """`body` cut to `limit` characters WITH its truncation marker inside that bound."""
    if limit <= 0:
        return ""
    if len(body) <= limit:
        return body
    reserve = min(80, max(0, limit // 4))
    content = body[: max(0, limit - reserve)].rstrip()
    marker = f"\n… truncated ({len(content)} of {len(body)} chars shown{tail})."
    out = content + marker
    if len(out) <= limit:
        return out
    room = max(0, limit - len(marker))
    return (content[:room].rstrip() + marker)[:limit]


def _label(root: Path, path: Path) -> str:
    try:
        return path.relative_to(root).as_posix()
    except ValueError:
        return path.name


_FRONTMATTER = re.compile(
    r"\A---[ \t]*\r?\n(.*?)\r?\n---[ \t]*(?:\r?\n|\Z)", re.DOTALL
)


def _clean_scalar(value: str) -> str:
    """One frontmatter scalar, unquoted and without a trailing YAML comment."""
    text = value.strip()
    if not text:
        return ""
    if text[0] in "\"'":
        end = text.find(text[0], 1)
        if end > 0:
            return text[1:end]
    cut = text.find(" #")
    if cut >= 0:
        text = text[:cut].rstrip()
    return text


def _paths_value(value: str) -> list[str] | None:
    text = value.strip()
    if text.startswith("["):
        if not text.endswith("]"):
            return None
        inner = text[1:-1].strip()
        if not inner:
            return []
        return [scalar for scalar in (_clean_scalar(part) for part in inner.split(",")) if scalar]
    scalar = _clean_scalar(text)
    return [scalar] if scalar else []


def _paths_from_frontmatter(block: str) -> list[str] | None:
    """The ``paths`` list of a frontmatter block, or None when it has none.

    Only the one key is read. A malformed value degrades to "no filter": a
    broken filter must not silently drop the user's own instructions.
    """
    lines = block.splitlines()
    for index, line in enumerate(lines):
        stripped = line.strip()
        if not stripped.startswith("paths:"):
            continue
        inline = stripped[len("paths:"):].strip()
        if inline:
            return _paths_value(inline)
        values: list[str] = []
        for follow in lines[index + 1:]:
            text = follow.strip()
            if not text or text.startswith("#"):
                continue
            if not text.startswith("-"):
                break
            scalar = _clean_scalar(text[1:])
            if scalar:
                values.append(scalar)
        return values
    return None


def _split_frontmatter(raw: str) -> tuple[list[str] | None, str]:
    match = _FRONTMATTER.match(raw)
    if match is None:
        return None, raw
    return _paths_from_frontmatter(match.group(1)), raw[match.end():]


@lru_cache(maxsize=256)
def _glob_regex(pattern: str) -> re.Pattern[str]:
    """A path-aware glob: ``*`` stays inside a segment, ``**`` crosses one."""
    out = ["^"]
    index = 0
    length = len(pattern)
    while index < length:
        char = pattern[index]
        if char == "*":
            if index + 1 < length and pattern[index + 1] == "*":
                index += 2
                if index < length and pattern[index] == "/":
                    out.append("(?:.*/)?")
                    index += 1
                else:
                    out.append(".*")
            else:
                out.append("[^/]*")
                index += 1
        elif char == "?":
            out.append("[^/]")
            index += 1
        elif char == "[":
            end = index + 1
            if end < length and pattern[end] in "!^":
                end += 1
            if end < length and pattern[end] == "]":
                end += 1
            while end < length and pattern[end] != "]":
                end += 1
            if end >= length:
                out.append(re.escape("["))
                index += 1
            else:
                body = pattern[index + 1:end]
                if body.startswith("!"):
                    body = "^" + body[1:]
                out.append("[" + body.replace("\\", "\\\\") + "]")
                index = end + 1
        else:
            out.append(re.escape(char))
            index += 1
    out.append("$")
    return re.compile("".join(out))


def _turn_paths(root: Path, paths: list[str] | str | None) -> list[str] | None:
    """Workspace-relative POSIX paths for one turn; None means no filtering.

    Absolute paths outside the workspace cannot match a workspace-relative
    glob, so they are dropped instead of being compared by their tail.
    """
    if paths is None:
        return None
    raw_paths = [paths] if isinstance(paths, str) else list(paths)
    out: list[str] = []
    for raw in raw_paths:
        text = str(raw or "").strip()
        if not text:
            continue
        candidate = Path(text).expanduser()
        if candidate.is_absolute():
            try:
                out.append(candidate.resolve().relative_to(root).as_posix())
            except (OSError, RuntimeError, ValueError):
                continue
            continue
        normalized = os.path.normpath(text).replace(os.sep, "/")
        if normalized in ("", ".", "..") or normalized.startswith("../"):
            continue
        while normalized.startswith("./"):
            normalized = normalized[2:]
        out.append(normalized)
    return out


def _paths_allow(patterns: list[str], turn_paths: list[str]) -> bool:
    return any(
        _glob_regex(pattern).match(path)
        for pattern in patterns
        for path in turn_paths
    )



def _read_file(root: Path, path: Path) -> tuple[str | None, str, str]:
    """Read one candidate. Status ``""`` means the file is simply absent."""
    from core.path_guard import denied, within

    try:
        if denied(path):
            return None, DENIED, "protected-root"
        # `within` compares resolved text, so both sides are resolved here first:
        # a symlink has to stay under the root it was announced in.
        real = path.resolve()
        if not within(real, root):
            return None, DENIED, "outside-root"
        if not path.is_file():
            return None, "", ""
        raw = real.read_text(encoding="utf-8")
    except (OSError, RuntimeError, UnicodeDecodeError) as exc:
        logger.warning("Workspace context unreadable at %s: %s", path, exc)
        return None, UNREADABLE, ""
    return raw, INCLUDED, ""


def _overlay_header(layer: str, path: Path) -> str:
    if layer == LAYER_SOUL:
        return f"## Persona for this workspace (from {path} — voice, tone and boundaries)\n\n"
    if layer == LAYER_USER:
        return f"## User preferences (from {path} — standing preferences that apply across turns)\n\n"
    return f"## Long-term memory (from {path} — curated notes from earlier sessions)\n\n"


def _read_overlay(
    root: Path,
    *,
    layer: str,
    candidates: tuple[Path, ...],
    cap: int,
    scope: str,
    shared_blocked: bool,
    parts: list[str],
    files: list[RuleFile],
    remaining: int,
) -> int:
    chosen_path: Path | None = None
    body: str | None = None
    status = ""
    reason = ""
    if shared_blocked:
        # A shared session must not even read a private file: existence is
        # enough to report that the layer stayed out.
        for path in candidates:
            if path.is_file():
                files.append(
                    RuleFile(_label(root, path), 0, SKIPPED, "shared-context", layer, scope)
                )
                break
        return remaining
    for path in candidates:
        raw, found_status, found_reason = _read_file(root, path)
        if not found_status:
            continue
        chosen_path, status, reason = path, found_status, found_reason
        body = raw
        break
    if chosen_path is None:
        return remaining

    name = _label(root, chosen_path)

    if status in (DENIED, UNREADABLE, EMPTY) or body is None:
        files.append(RuleFile(name, 0, status or EMPTY, reason, layer, scope))
        return remaining

    body = body.strip()
    if not body:
        files.append(RuleFile(name, 0, EMPTY, "", layer, scope))
        return remaining

    if len(body) > cap:
        body = _bounded(body, cap)
        status = TRUNCATED
    header = _overlay_header(layer, chosen_path)
    separator = 2 if parts else 0
    room = remaining - len(header) - separator
    if room <= 0:
        files.append(RuleFile(name, 0, SKIPPED, "no-budget", layer, scope))
        return remaining
    if len(body) > room:
        body = _bounded(body, room, "; combined cap")
        status = TRUNCATED
    piece = header + body
    used = len(piece) + separator
    files.append(RuleFile(name, len(body), status, reason, layer, scope))
    parts.append(piece)
    return remaining - used


def read_workspace_rules(
    paths: list[str] | str | None = None,
    *,
    shared: bool = False,
) -> WorkspaceRules:
    """Read every context layer the workspace carries; report what each one did.

    A file under a deny root, a symlink leaving its root, an unreadable file and
    an empty one are all skipped — and named, with a stable reason, so the
    display can say why the model did not see them.

    ``paths`` is the current turn's workspace-relative context (for example the
    files a request names). Without it a rule file whose frontmatter declares
    ``paths:`` loads exactly as an unscoped rule does. ``shared=True`` marks a
    shared session: ``MEMORY.md`` stays out and is reported with its reason.
    """
    from core.path_guard import denied, within

    root = Path(resolve_workspace_dir() or ".").expanduser()
    try:
        root = root.resolve()
    except OSError:
        return WorkspaceRules(text=None)

    rules_dir = (root / RULES_DIR).resolve()
    turn_paths = _turn_paths(root, paths)
    remaining = WORKSPACE_CONTEXT_MAX
    rules_budget = min(WORKSPACE_RULES_MAX, remaining)
    parts: list[str] = []
    files: list[RuleFile] = []

    for path in _candidates(root):
        name = _label(root, path)
        layer = LAYER_AGENTS if path.parent == root else LAYER_RULES
        try:
            if denied(path):
                files.append(RuleFile(name, 0, DENIED, "protected-root", layer, SCOPE_WORKSPACE))
                continue
            real = path.resolve()
            if not within(real, root) or (
                path.parent != root and not within(real, rules_dir)
            ):
                files.append(RuleFile(name, 0, DENIED, "outside-root", layer, SCOPE_WORKSPACE))
                continue
            if not path.is_file():
                continue
            raw = real.read_text(encoding="utf-8")
        except (OSError, RuntimeError, UnicodeDecodeError) as exc:
            logger.warning("Workspace rules unreadable at %s: %s", path, exc)
            files.append(RuleFile(name, 0, UNREADABLE, "", layer, SCOPE_WORKSPACE))
            continue

        if layer == LAYER_RULES:
            path_filter, raw = _split_frontmatter(raw)
            if (
                path_filter is not None
                and turn_paths is not None
                and not _paths_allow(path_filter, turn_paths)
            ):
                files.append(
                    RuleFile(name, 0, SKIPPED, "path-filter", layer, SCOPE_WORKSPACE)
                )
                continue

        body = raw.strip()
        if not body:
            files.append(RuleFile(name, 0, EMPTY, "", layer, SCOPE_WORKSPACE))
            continue
        status = INCLUDED
        if len(body) > RULE_FILE_MAX:
            body = _bounded(body, RULE_FILE_MAX)
            status = TRUNCATED
        header = f"## Project rules (from {path} — treat as the user's own instructions)\n\n"
        # The combined cap bounds the text the prompt receives, markers and provenance
        # included; only what actually fits is announced as included.
        separator = 2 if parts else 0
        room = min(rules_budget, remaining) - len(header) - separator
        if room <= 0:
            files.append(RuleFile(name, 0, SKIPPED, "no-budget", layer, SCOPE_WORKSPACE))
            continue
        if len(body) > room:
            body = _bounded(body, room, "; combined cap")
            status = TRUNCATED
        piece = header + body
        used = len(piece) + separator
        rules_budget -= used
        remaining -= used
        files.append(RuleFile(name, len(body), status, "", layer, SCOPE_WORKSPACE))
        parts.append(piece)

    remaining = _read_overlay(
        root,
        layer=LAYER_SOUL,
        candidates=(root / SOUL_NAME, root / PERSONA_ALIAS),
        cap=SOUL_FILE_MAX,
        scope=SCOPE_WORKSPACE,
        shared_blocked=False,
        parts=parts,
        files=files,
        remaining=remaining,
    )
    remaining = _read_overlay(
        root,
        layer=LAYER_USER,
        candidates=(root / USER_NAME, root / USER_ALIAS),
        cap=USER_FILE_MAX,
        scope=SCOPE_WORKSPACE,
        shared_blocked=False,
        parts=parts,
        files=files,
        remaining=remaining,
    )
    _read_overlay(
        root,
        layer=LAYER_MEMORY,
        candidates=(root / MEMORY_NAME,),
        cap=MEMORY_FILE_MAX,
        scope=SCOPE_PRIVATE,
        shared_blocked=shared,
        parts=parts,
        files=files,
        remaining=remaining,
    )

    return WorkspaceRules(text="\n\n".join(parts) if parts else None, files=tuple(files))


def load_workspace_rules(
    paths: list[str] | str | None = None,
    *,
    shared: bool = False,
) -> str | None:
    """The prompt-side view: the same resolver, text only."""
    return read_workspace_rules(paths, shared=shared).text


def explain_workspace_context(
    paths: list[str] | str | None = None,
    *,
    shared: bool = False,
) -> dict:
    """The UI/CLI view: every layer with its file, size, status and scope.

    ``layers`` lists only files the resolver found; an absent optional overlay
    is not a layer. ``total_chars`` is the assembled text, headers included, so
    it can never read larger than ``caps.total``.
    """
    result = read_workspace_rules(paths, shared=shared)
    return {
        "layers": [
            {
                "name": entry.layer,
                "file": entry.name,
                "chars": entry.chars,
                "status": entry.status,
                "reason": entry.reason,
                "scope": entry.scope,
            }
            for entry in result.files
        ],
        "caps": {
            "total": WORKSPACE_CONTEXT_MAX,
            "per_file": dict(LAYER_CAPS),
        },
        "total_chars": result.total_chars,
    }
